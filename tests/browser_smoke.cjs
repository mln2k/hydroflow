/* Запуск: NODE_PATH=<каталог с playwright> node tests/browser_smoke.cjs
   Нужен запущенный сервер и HF_TEST_PASSWORD; тест создаёт данные. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:process.env.HF_BROWSER_CHANNEL||undefined});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('401'))errors.push(m.text());});
  await page.goto(process.env.HF_TEST_URL||'http://127.0.0.1:8000');
  await page.getByLabel('Электронная почта').fill(process.env.HF_TEST_EMAIL||'admin@example.local');
  await page.getByLabel('Пароль',{exact:true}).fill(process.env.HF_TEST_PASSWORD);
  await page.getByRole('button',{name:'Войти',exact:true}).click();
  await page.getByRole('heading',{name:'Проекты',exact:true}).waitFor();
  await page.getByRole('button',{name:'+ Новый проект'}).click();
  const project='UI проверка '+Date.now();
  await page.getByLabel('Название',{exact:true}).fill(project);
  await page.getByLabel('Описание',{exact:true}).fill('Проверка сценариев через браузер');
  await page.getByRole('button',{name:'Сохранить',exact:true}).click();
  await page.getByRole('heading',{name:project}).waitFor();
  await page.getByRole('button',{name:'Требования',exact:true}).click();
  await page.getByRole('button',{name:'+ Требование',exact:true}).click();
  await page.getByLabel('Код требования').fill('REQ-UI');
  await page.getByLabel('Название',{exact:true}).fill('Требование браузерной проверки');
  await page.getByLabel('Описание',{exact:true}).fill('Исходное описание');
  await page.getByRole('button',{name:'Сохранить',exact:true}).click();
  await page.getByRole('button',{name:'Требование браузерной проверки',exact:true}).click();
  await page.getByRole('button',{name:'Редактировать',exact:true}).click();
  await page.getByLabel('Описание',{exact:true}).fill('Уточнённое описание');
  await page.getByLabel('Причина изменения').fill('Проверка версионности');
  await page.getByRole('button',{name:'Сохранить',exact:true}).click();
  await page.getByRole('button',{name:'Требование браузерной проверки',exact:true}).click();
  await page.getByLabel('Комментарий',{exact:true}).fill('Проверка обсуждения');
  await page.getByRole('button',{name:'Отправить',exact:true}).click();
  await page.getByText('Проверка обсуждения',{exact:true}).waitFor();
  await page.getByRole('button',{name:'История версий',exact:true}).click();
  await page.getByRole('heading',{name:/Версия 2/}).waitFor();
  await page.getByText('Исходное описание',{exact:false}).waitFor();
  await page.getByRole('button',{name:'Закрыть',exact:true}).click();
  await page.getByRole('button',{name:'Задачи',exact:true}).click();
  await page.getByRole('button',{name:'+ Задача',exact:true}).click();
  await page.getByLabel('Название',{exact:true}).fill('Задача браузерной проверки');
  await page.getByLabel('Требование',{exact:true}).selectOption({label:'REQ-UI · Требование браузерной проверки'});
  await page.getByRole('button',{name:'Сохранить',exact:true}).click();
  await page.getByRole('button',{name:'Задача браузерной проверки',exact:true}).click();
  await page.getByRole('button',{name:'Назначить исполнителей',exact:true}).click();
  await page.getByRole('checkbox').first().check();
  await page.getByRole('button',{name:'Сохранить',exact:true}).click();
  await page.getByLabel('Статус задачи Задача браузерной проверки').selectOption('done');
  await page.locator('.column').filter({hasText:'Завершена'}).getByRole('button',{name:'Задача браузерной проверки',exact:true}).waitFor();
  await page.getByRole('button',{name:'Документы',exact:true}).click();
  await page.getByRole('button',{name:'+ Документ',exact:true}).click();
  await page.getByLabel('Название',{exact:true}).fill('Файл браузерной проверки');
  await page.getByLabel('Файл (до 5 МиБ)').setInputFiles({name:'sample.txt',mimeType:'text/plain',buffer:Buffer.from('Проверка файла')});
  await page.getByRole('button',{name:'Сохранить',exact:true}).click();
  await page.getByRole('button',{name:'Файл браузерной проверки',exact:true}).click();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Скачать sample.txt',exact:true}).click();
  const download=await downloadPromise;assert.equal(download.suggestedFilename(),'sample.txt');
  await page.getByRole('button',{name:'Закрыть',exact:true}).click();
  await page.getByRole('button',{name:'Отчёты',exact:true}).click();
  await page.getByRole('heading',{name:'Влияние изменений требований'}).waitFor();
  await page.getByText('Есть завершённые задачи.',{exact:false}).waitFor();
  await page.getByRole('button',{name:'Обзор',exact:true}).click();
  await page.screenshot({path:process.env.HF_SCREENSHOT||'/tmp/hydroflow-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Горизонтальный скролл страницы');
  await page.screenshot({path:process.env.HF_MOBILE_SCREENSHOT||'/tmp/hydroflow-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await browser.close();console.log('Browser smoke: OK — проект, версии, комментарии, назначения, файл, отчёт, мобильная вёрстка');
})().catch(e=>{console.error(e);process.exit(1);});
